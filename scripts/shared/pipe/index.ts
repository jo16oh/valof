type Step<A, B> = (a: A) => B;
type AsyncStep<A, B> = (a: Awaited<A>) => B;

/**
 * A last step of {@link flow} that takes the chain's promise rather than its value. Extend it with
 * an `out` written in terms of `this["in"]`, the promise's type, to type what `sink` returns.
 */
export interface Sink {
  readonly in: unknown;
  readonly out: unknown;
  readonly sink: (promise: never) => unknown;
}

// Reads `out` with `in` set to `P`: a type-level call, since `sink` alone cannot carry a
// return type that depends on the promise.
type Apply<F extends Sink, P> = (F & { readonly in: P })["out"];

